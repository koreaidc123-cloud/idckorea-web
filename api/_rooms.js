/* ═══════════════════════════════════════════════════════════════
   서버실 구조 — 서버와 화면이 같은 값을 봅니다

   ★ 왜 필요한가
     랙 수·층수·자리수가 admin.html 안에만 있었습니다. 서버는 아무것도
     몰라서 rack 은 1~999, fl 은 1~99 면 무조건 통과시켰습니다.
     그래서 현장 등록 프로그램이 "등원리 99번 랙" 을 보내도 그대로 저장됐고,
     실제로 엉뚱한 서버실 엉뚱한 자리에 한 대가 등록됐습니다.
     (2026-08-17 현장에서 확인)

     자리를 받는 곳은 전부 여기를 거칩니다 — 현장 등록(pc-register)과
     관리자 수정(_admin-pc-update).

   ※ 서버실 실명은 오류 문구에만 씁니다. 고객 화면에는 절대 나가지 않습니다.
     (고객에게는 품번 앞글자 K / Y / D 만 보입니다)

   ※ 랙을 늘리시면 여기 racks 숫자와 admin.html 의 ROOMS 를 같이 고치셔야
     합니다. 두 곳이 어긋나면 화면에는 보이는데 저장이 거부됩니다.
   ═══════════════════════════════════════════════════════════════ */

const ROOMS = {
  K: { name: '금촌',   racks: 7 },
  Y: { name: '영태리', racks: 9 },
  D: { name: '등원리', racks: 6 },
};

const FLOORS = 4;    // 랙 한 대당 층수 (1층 = 맨 아래)
const SLOTS  = 14;   // 한 층당 자리 수 (1번 = 오른쪽 끝)

/* 그 서버실에 실제로 있는 자리인지 봅니다.
   맞으면 null, 틀리면 현장에서 바로 알아볼 수 있는 문장을 돌려줍니다. */
function checkLoc(room, rack, fl, slot) {
  const r = ROOMS[room];
  if (!r) return '서버실은 금촌(K) · 영태리(Y) · 등원리(D) 중 하나여야 합니다';
  if (!(rack >= 1 && rack <= r.racks)) {
    return `${r.name}에는 1번 ~ ${r.racks}번 랙까지 있습니다. ${rack}번 랙은 없습니다.\n` +
           `서버실을 잘못 고르셨는지 먼저 확인해 주세요.`;
  }
  if (!(fl >= 1 && fl <= FLOORS)) {
    return `랙은 1층 ~ ${FLOORS}층입니다. ${fl}층은 없습니다.`;
  }
  if (!(slot >= 1 && slot <= SLOTS)) {
    return `한 층은 1번 ~ ${SLOTS}번 자리입니다. ${slot}번 자리는 없습니다.\n` +
           `자리 1번은 오른쪽 끝입니다.`;
  }
  return null;
}

module.exports = { ROOMS, FLOORS, SLOTS, checkLoc };
