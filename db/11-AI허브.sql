-- ── 1. 모아 올 곳 ─────────────────────────────────────────────
create table if not exists hub_sources (
  id                bigint generated by default as identity primary key,
  kind              text not null check (kind in ('rss', 'youtube')),
  name              text not null,
  url_or_channel_id text not null unique,   -- rss = https 주소 · youtube = UC 로 시작하는 채널 번호
  topic             text,
  enabled           boolean not null default true,
  created_at        timestamptz not null default now()
);

-- ── 2. 모아 온 글 ─────────────────────────────────────────────
create table if not exists hub_items (
  id           bigint generated by default as identity primary key,
  source_id    bigint references hub_sources(id) on delete set null,
  kind         text not null check (kind in ('news', 'youtube')),
  title        text not null,
  url          text not null unique,          -- 같은 글은 한 줄만 (다시 모아도 덮어씀)
  summary      text check (summary is null or char_length(summary) <= 200),   -- 글자만 (태그 없음)
  thumb        text,
  published_at timestamptz,
  views        bigint,
  score        double precision not null default 0,   -- 유튜브 = 올린 뒤 시간당 조회수
  hidden       boolean not null default false,        -- 관리자가 숨긴 글
  pinned       boolean not null default false,        -- 관리자가 맨 위로 고정한 글 (30일이 지나도 안 지움)
  created_at   timestamptz not null default now()
);
create index if not exists hub_items_kind_pub on hub_items (kind, published_at desc);
create index if not exists hub_items_kind_score on hub_items (kind, score desc);

-- ── 3. 오늘의 AI 브리핑 ───────────────────────────────────────
create table if not exists hub_briefs (
  id           bigint generated by default as identity primary key,
  day          date not null unique,
  title        text not null,
  body         text not null,                 -- 글자만 (제목 # · 목록 - 정도만 씀)
  status       text not null default 'draft' check (status in ('draft', 'published')),
  source       text not null default 'admin' check (source in ('ai_hq', 'admin')),
  created_at   timestamptz not null default now(),
  published_at timestamptz,
  who          text
);

-- ── 4. 보안 — 정책 없음 = 서버만 ─────────────────────────────
alter table hub_sources enable row level security;
alter table hub_items   enable row level security;
alter table hub_briefs  enable row level security;

